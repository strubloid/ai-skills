#!/usr/bin/env bash
# install.sh - Install/update AI tool skills from this repo to target configs.
#
# Usage:
#   ./install.sh                     # interactive setup + initial sync
#   ./install.sh --reconfigure       # change which targets are enabled
#   ./install.sh --sync              # run the same sync as `update-skills`
#   ./install.sh --dry-run           # show what --sync would change
#   ./install.sh --status            # show state and per-target status
#   ./install.sh --help              # this help
#
# After running once, the `update-skills` command is available on PATH.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STATE_DIR="${SKILLS_SYNC_STATE_DIR:-$HOME/.config/skills-sync}"
STATE_FILE="$STATE_DIR/state.conf"
UPDATE_CMD_DIR="$HOME/.local/bin"
UPDATE_CMD_PATH="$UPDATE_CMD_DIR/update-skills"

# Known tools -> default skill directory.
declare -A TOOL_DEFAULTS=(
  [opencode]="$HOME/.config/opencode/skills"
  [codex]="$HOME/.codex/skills"
  [hermes]="$HOME/.hermes/skills"
)

# Live in-memory state (sourced from $STATE_FILE each run).
SKILLS_SOURCE=""
SKILLS_TARGETS=()    # entries: "tool|path|enabled(0|1)"
SKILLS_INSTALLED=()  # names of skills we've installed into each target

log()  { printf '\033[1;34m[skills]\033[0m %s\n' "$*" >&2; }
warn() { printf '\033[1;33m[skills]\033[0m %s\n' "$*" >&2; }
err()  { printf '\033[1;31m[skills]\033[0m %s\n' "$*" >&2; }
die()  { err "$*"; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "missing dependency: $1"; }

# ---------------------------------------------------------------------------
# State management: bash-sourceable conf file, no JSON parser needed.

state_init() {
  mkdir -p "$STATE_DIR"
  if [[ ! -f "$STATE_FILE" ]]; then
    SKILLS_SOURCE="$SCRIPT_DIR"
    SKILLS_TARGETS=()
    SKILLS_INSTALLED=()
    state_save
    return
  fi
  # shellcheck disable=SC1090
  source "$STATE_FILE"
  [[ -z "${SKILLS_SOURCE:-}" ]] && SKILLS_SOURCE="$SCRIPT_DIR"
  : "${SKILLS_TARGETS:=()}"
  : "${SKILLS_INSTALLED:=()}"
}

state_save() {
  local tmp
  tmp="$(mktemp)"
  {
    printf '# Auto-generated by skills/install.sh — do not edit by hand.\n'
    printf 'SKILLS_SOURCE=%q\n' "$SKILLS_SOURCE"
    printf 'SKILLS_TARGETS=(\n'
    local e tool path en
    for e in "${SKILLS_TARGETS[@]}"; do
      IFS='|' read -r tool path en <<<"$e"
      printf '  %q\n' "$e"
    done
    printf ')\n'
    printf 'SKILLS_INSTALLED=(\n'
    for s in "${SKILLS_INSTALLED[@]}"; do
      printf '  %q\n' "$s"
    done
    printf ')\n'
  } >"$tmp"
  mv "$tmp" "$STATE_FILE"
}

target_lookup_path()  { local e; for e in "${SKILLS_TARGETS[@]}"; do [[ "${e%%|*}" == "$1" ]] && { echo "${e#*|}"; return; }; done; }
target_is_enabled()  { local e; for e in "${SKILLS_TARGETS[@]}"; do [[ "${e%%|*}" == "$1" ]] && { [[ "${e##*|}" == "1" ]] && return 0 || return 1; }; done; return 1; }

target_set() {
  local tool="$1" path="$2" en="${3:-1}"
  local new=() e tool_e path_e en_e found=0
  for e in "${SKILLS_TARGETS[@]:-}"; do
    [[ -z "$e" ]] && continue
    IFS='|' read -r tool_e path_e en_e <<<"$e"
    if [[ "$tool_e" == "$tool" ]]; then
      new+=("$tool|$path|$en")
      found=1
    else
      new+=("$e")
    fi
  done
  (( found )) || new+=("$tool|$path|$en")
  SKILLS_TARGETS=("${new[@]}")
}

target_remove() {
  local tool="$1" new=() e tool_e
  for e in "${SKILLS_TARGETS[@]:-}"; do
    [[ -z "$e" ]] && continue
    IFS='|' read -r tool_e _ <<<"$e"
    [[ "$tool_e" == "$tool" ]] || new+=("$e")
  done
  SKILLS_TARGETS=("${new[@]}")
}

# ---------------------------------------------------------------------------
# Skill discovery.

list_source_skills() {
  local source="${1:-$SKILLS_SOURCE}"
  [[ -d "$source" ]] || return 0
  local d name
  for d in "$source"/*/; do
    [[ -d "$d" ]] || continue
    [[ -f "$d/SKILL.md" ]] || continue
    name="$(basename "$d")"
    [[ "$name" == .git ]] && continue
    printf '%s\n' "$name"
  done | sort -u
}

# ---------------------------------------------------------------------------
# Diff helpers.

# Print sha256 sums of all regular files under $1 (excluding .git), sorted.
dir_fingerprint() {
  ( cd "$1" && find . -type f ! -path './.git/*' ! -path './.git' -exec sha256sum {} + 2>/dev/null | LC_ALL=C sort )
}

# ---------------------------------------------------------------------------
# Sync engine.

sync_target() {
  local source="$1" target_path="$2" dry_run="${3:-0}"
  local added=0 updated=0 removed=0 unchanged=0
  local src_skills=() name src_dir dst_dir present
  local installed_arr=()
  local e tool_e

  mkdir -p "$target_path"

  # Build list of source skills.
  while IFS= read -r name; do
    [[ -n "$name" ]] && src_skills+=("$name")
  done < <(list_source_skills "$source")

  # Add / update.
  for name in "${src_skills[@]}"; do
    src_dir="$source/$name"
    dst_dir="$target_path/$name"
    if [[ ! -d "$dst_dir" ]]; then
      log "  + add   $name"
      if (( !dry_run )); then
        mkdir -p "$dst_dir"
        rsync -a --exclude='.git/' "$src_dir/" "$dst_dir/"
      fi
      added=$((added+1))
    elif ! cmp -s <(dir_fingerprint "$src_dir") <(dir_fingerprint "$dst_dir"); then
      log "  ~ update $name"
      if (( !dry_run )); then
        rsync -a --exclude='.git/' --delete "$src_dir/" "$dst_dir/"
      fi
      updated=$((updated+1))
    else
      unchanged=$((unchanged+1))
    fi
  done

  # Remove skills we previously installed that are gone from source.
  for name in "${SKILLS_INSTALLED[@]:-}"; do
    present=0
    for s in "${src_skills[@]}"; do
      [[ "$s" == "$name" ]] && { present=1; break; }
    done
    if (( !present )) && [[ -d "$target_path/$name" ]]; then
      log "  - drop  $name"
      if (( !dry_run )); then
        rm -rf "$target_path/$name"
      fi
      removed=$((removed+1))
    fi
  done

  printf '%d\t%d\t%d\t%d\n' "$added" "$updated" "$removed" "$unchanged"
}

sync_all() {
  local dry_run="${1:-0}"
  need rsync

  log "source: $SKILLS_SOURCE"
  if (( ${#SKILLS_TARGETS[@]} == 0 )); then
    warn "no targets configured. run: $0 --reconfigure"
    return 0
  fi

  local e tool path en grand_added=0 grand_updated=0 grand_removed=0 grand_unchanged=0
  local stats a u r n
  for e in "${SKILLS_TARGETS[@]}"; do
    IFS='|' read -r tool path en <<<"$e"
    if [[ "$en" != "1" ]]; then
      log "skip  $tool ($path) - disabled"
      continue
    fi
    log "sync  $tool -> $path"
    stats="$(sync_target "$SKILLS_SOURCE" "$path" "$dry_run")"
    IFS=$'\t' read -r a u r n <<<"$stats"
    grand_added=$((grand_added+a))
    grand_updated=$((grand_updated+u))
    grand_removed=$((grand_removed+r))
    grand_unchanged=$((grand_unchanged+n))
    printf '       +%d added  ~%d updated  -%d removed  =%d unchanged\n' "$a" "$u" "$r" "$n"
  done

  # Update installed_skills to current source set.
  SKILLS_INSTALLED=()
  while IFS= read -r name; do
    [[ -n "$name" ]] && SKILLS_INSTALLED+=("$name")
  done < <(list_source_skills "$SKILLS_SOURCE")

  if (( !dry_run )); then
    state_save
  fi

  echo
  log "done. +${grand_added} added, ~${grand_updated} updated, -${grand_removed} removed, =${grand_unchanged} unchanged"
}

# ---------------------------------------------------------------------------
# Install / reconfigure.

install_update_command() {
  mkdir -p "$UPDATE_CMD_DIR"
  cat >"$UPDATE_CMD_PATH" <<EOF
#!/usr/bin/env bash
# Auto-generated by skills/install.sh — do not edit by hand.
# Runs sync from: $SKILLS_SOURCE
exec "$SCRIPT_DIR/install.sh" --sync "\$@"
EOF
  chmod +x "$UPDATE_CMD_PATH"
  log "installed command: $UPDATE_CMD_PATH"
  if [[ ":$PATH:" != *":$UPDATE_CMD_DIR:"* ]]; then
    warn "$UPDATE_CMD_DIR is not on PATH — add to your shell rc."
  fi
}

# Silent re-install — only logs on first creation.
ensure_update_command() {
  local content
  content=$(cat <<EOF
#!/usr/bin/env bash
# Auto-generated by skills/install.sh — do not edit by hand.
# Runs sync from: $SKILLS_SOURCE
# Default action is --sync; pass --dry-run, --status, etc. to override.
[[ \$# -eq 0 ]] && set -- --sync
exec "$SCRIPT_DIR/install.sh" "\$@"
EOF
)
  if [[ ! -x "$UPDATE_CMD_PATH" ]] || [[ "$content" != "$(cat "$UPDATE_CMD_PATH" 2>/dev/null)" ]]; then
    mkdir -p "$UPDATE_CMD_DIR"
    printf '%s\n' "$content" >"$UPDATE_CMD_PATH"
    chmod +x "$UPDATE_CMD_PATH"
  fi
}

configure_targets() {
  echo
  log "== configure targets =="
  echo "Source: $SKILLS_SOURCE"
  echo

  # Merge defaults with anything already configured.
  local existing_tools=()
  local e tool_e
  for e in "${SKILLS_TARGETS[@]:-}"; do
    [[ -z "$e" ]] && continue
    IFS='|' read -r tool_e _ <<<"$e"
    existing_tools+=("$tool_e")
  done

  for tool in "${!TOOL_DEFAULTS[@]}"; do
    local found=0
    for t in "${existing_tools[@]}"; do
      [[ "$t" == "$tool" ]] && { found=1; break; }
    done
    (( found )) || SKILLS_TARGETS+=("$tool|${TOOL_DEFAULTS[$tool]}|1")
  done

  local i=1
  echo "Detected tools:"
  for e in "${SKILLS_TARGETS[@]}"; do
    IFS='|' read -r tool path en <<<"$e"
    printf '  %d) %-10s %s [%s]\n' "$i" "$tool" "$path" "$([[ "$en" == "1" ]] && echo enabled || echo disabled)"
    i=$((i+1))
  done
  echo

  for e in "${SKILLS_TARGETS[@]}"; do
    IFS='|' read -r tool path en <<<"$e"
    local ans new_en new_path="$path"
    read -r -p "Install skills to $tool ($path)? [Y=enable / n=disable / custom-path] " ans
    case "$ans" in
      n|N|no|NO|"") new_en=0 ;;
      /*)             new_en=1; new_path="$ans" ;;
      *)              new_en=1 ;;
    esac
    target_set "$tool" "$new_path" "$new_en"
  done

  echo
  local extra_tool extra_path
  read -r -p "Add a custom target (tool name, blank to skip)? " extra_tool
  if [[ -n "$extra_tool" ]]; then
    read -r -p "Path: " extra_path
    [[ -n "$extra_path" ]] || die "path required"
    target_set "$extra_tool" "$extra_path" 1
  fi

  # Persist immediately so the install command captures the right source path.
  state_save
  log "saved config to $STATE_FILE"
}

show_status() {
  echo
  log "== status =="
  echo "source: $SKILLS_SOURCE"
  echo
  echo "targets:"
  local e tool path en
  for e in "${SKILLS_TARGETS[@]:-}"; do
    [[ -z "$e" ]] && continue
    IFS='|' read -r tool path en <<<"$e"
    local mark="x"
    [[ "$en" == "1" ]] && mark="*"
    printf '  [%s] %-10s %s\n' "$mark" "$tool" "$path"
  done
  echo
  echo "source skills: $(list_source_skills | wc -l)"
  echo "managed skills: ${#SKILLS_INSTALLED[@]}"
  echo "update-skills: $UPDATE_CMD_PATH $( [[ -x "$UPDATE_CMD_PATH" ]] && echo "(installed)" || echo "(missing)" )"
  echo
  if [[ -x "$UPDATE_CMD_PATH" ]] && [[ ":$PATH:" != *":$UPDATE_CMD_DIR:"* ]]; then
    warn "$UPDATE_CMD_DIR is not on PATH — add to shell rc"
  fi
}

usage() {
  cat <<EOF
install.sh — sync skills folder to one or more tool directories.

  ./install.sh                  interactive install + initial sync
  ./install.sh --reconfigure    change which tools are enabled
  ./install.sh --sync           run sync (same as 'update-skills')
  ./install.sh --dry-run        show what --sync would change
  ./install.sh --status         show current config
  ./install.sh --help           this help

After install, use \`update-skills\` anytime to push changes.
EOF
}

main() {
  need rsync
  need find
  need cmp
  state_init
  ensure_update_command

  case "${1:-}" in
    ""|--install)
      configure_targets
      sync_all 0
      show_status
      ;;
    --reconfigure)
      configure_targets
      sync_all 0
      ;;
    --sync)
      sync_all 0
      ;;
    --dry-run|-n)
      sync_all 1
      ;;
    --status)
      show_status
      ;;
    --help|-h)
      usage
      ;;
    *)
      usage
      exit 1
      ;;
  esac
}

main "$@"